// Generate UTF-8 decoder data from the original WordPress map and stable PHP tables.
$root = dirname(__DIR__);

/** Export strings as bytes so generated PHP remains independent of source encoding. */
function entity_fixture_literal(mixed $value): string {
    if (!is_string($value)) return var_export($value, true);
    $result = '"';
    for ($at = 0; $at < strlen($value); ++$at) {
        $byte = ord($value[$at]);
        $result .= $byte >= 32 && $byte <= 126 && !str_contains('"$\\', $value[$at])
            ? $value[$at]
            : '\\x' . str_pad(dechex($byte), 2, '0', STR_PAD_LEFT);
    }
    return $result . '"';
}
if (PHP_VERSION_ID < 80400 || PHP_VERSION_ID >= 80600) {
    throw new RuntimeException('Regenerate the entity fixture with PHP 8.4 or 8.5.');
}
$sources = array(
    'wp-includes/class-wp-token-map.php',
    'wp-includes/html-api/html5-named-character-references.php',
);
