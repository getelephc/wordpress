$provenance = $root . '/elephc/full-source/entities-provenance.json';
if (in_array('--check', $argv, true)) {
    if (file_get_contents($root . '/' . $fixture) !== $output || file_get_contents($provenance) !== $encoded) {
        throw new RuntimeException('The generated entity fixture or provenance differs.');
