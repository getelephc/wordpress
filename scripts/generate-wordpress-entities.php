$modes = array(ENT_HTML401, ENT_XML1, ENT_XHTML, ENT_HTML5);
$names = array();
$named_exceptions = array();
foreach ($html5_named_character_references->to_array() as $name => $value) {
    if (!str_ends_with($name, ';')) continue;
    $mask = 0;
    foreach ($modes as $index => $mode) {
        $decoded = html_entity_decode('&' . $name, ENT_QUOTES | $mode, 'UTF-8');
        if ($decoded === '&' . $name) continue;
        $bit = 1 << $index;
        if ($decoded !== $value) $named_exceptions[$bit . ':' . $name] = $decoded;
        $mask |= $bit;
    }
    if ($mask) $names[$name] = array($value, $mask);
}
ksort($names, SORT_STRING);
$ranges = array();
$exceptions = array();
$previous = -1;
$start = 0;
for ($point = 0; $point <= 0x10FFFF; ++$point) {
    $entity = '&#' . $point . ';';
    $expected = mb_chr($point, 'UTF-8');
    $mask = 0;
    foreach ($modes as $index => $mode) {
        $decoded = html_entity_decode($entity, ENT_QUOTES | $mode, 'UTF-8');
        if ($decoded === $entity) continue;
        $bit = 1 << $index;
        $mask |= $bit;
        if ($decoded !== $expected) $exceptions[$bit . ':' . $point] = $decoded;
    }
    if ($mask !== $previous) {
        if ($previous > 0) $ranges[] = array($start, $point - 1, $previous);
        $start = $point;
        $previous = $mask;
    }
}
if ($previous > 0) $ranges[] = array($start, 0x10FFFF, $previous);
$output = "<?php\n\n// Generated by scripts/generate-wordpress-entities.php.\n";
foreach (array('named' => $names, 'named_exceptions' => $named_exceptions, 'ranges' => $ranges, 'exceptions' => $exceptions) as $kind => $rows) {
