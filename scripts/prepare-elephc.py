#!/usr/bin/env python3
"""Fetch pinned WordPress sources and materialize the verified parser patches."""

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import tarfile
import tempfile
import urllib.request


ROOT = Path(__file__).resolve().parent.parent
UPSTREAM = ROOT / "upstream/wordpress"
CORE = ROOT / "elephc/runtime/core"
MARKER = ".elephc-generated"


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def expect_hash(path, expected):
    if not path.is_file() or digest(path) != expected:
        raise SystemExit(f"Missing file or checksum mismatch: {path}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify existing sources without writing or downloading")
    arguments = parser.parse_args()
    upstream = json.loads((ROOT / "elephc/upstream.json").read_text())
    manifest = json.loads((ROOT / "patches/manifest.json").read_text())
    archive = ROOT / "upstream" / f"wordpress-{upstream['version']}.tar.gz"

    if not archive.exists() and not arguments.check:
        archive.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix=".download-", dir=archive.parent) as directory:
            staged = Path(directory) / archive.name
            print(f"Downloading {upstream['url']}", flush=True)
            with urllib.request.urlopen(upstream["url"], timeout=60) as response, staged.open("wb") as target:
                shutil.copyfileobj(response, target)
            expect_hash(staged, upstream["archive_sha256"])
            staged.rename(archive)
    expect_hash(archive, upstream["archive_sha256"])

    if UPSTREAM.is_symlink():
        raise SystemExit(f"Refusing an upstream symlink: {UPSTREAM}")
    if not UPSTREAM.exists() and not arguments.check:
        with tempfile.TemporaryDirectory(prefix=".extract-", dir=archive.parent) as directory:
            with tarfile.open(archive) as package:
                package.extractall(directory, filter="data")
            (Path(directory) / "wordpress").rename(UPSTREAM)
    for path, checksum in upstream["verified_sources"].items():
        expect_hash(UPSTREAM / path, checksum)
    for entry in manifest["files"]:
        expect_hash(UPSTREAM / entry["path"], entry["original_sha256"])
        expect_hash(ROOT / entry["patch"], entry["patch_sha256"])

    if CORE.is_symlink():
        raise SystemExit(f"Refusing a generated source symlink: {CORE}")
    if arguments.check:
        expected = {entry["path"] for entry in manifest["files"]}
        actual = {str(path.relative_to(CORE)) for path in CORE.rglob("*.php")}
        if actual != expected:
            raise SystemExit("Generated source inventory differs. Run scripts/prepare-elephc.py.")
        for entry in manifest["files"]:
            expect_hash(CORE / entry["path"], entry["patched_sha256"])
        print(f"Verified WordPress {upstream['version']}, {len(expected)} core files and {len(expected)} patches.")
        return

    with tempfile.TemporaryDirectory(prefix=".core-", dir=CORE.parent) as directory:
        stage = Path(directory) / "core"
        stage.mkdir()
        for entry in manifest["files"]:
            target = stage / entry["path"]
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(UPSTREAM / entry["path"], target)
            subprocess.run(
                ["patch", "--batch", "--forward", "--fuzz=0", "-p1", "-d", str(stage)],
                input=(ROOT / entry["patch"]).read_bytes(), check=True, capture_output=True,
            )
            expect_hash(target, entry["patched_sha256"])
        (stage / MARKER).write_text("Generated by scripts/prepare-elephc.py.\n")
        if CORE.exists():
            if not (CORE / MARKER).is_file():
                raise SystemExit(f"Refusing to replace an unmarked directory: {CORE}")
            shutil.rmtree(CORE)
        stage.rename(CORE)
    print(f"Prepared WordPress {upstream['version']} parser profile.")


if __name__ == "__main__":
    main()
